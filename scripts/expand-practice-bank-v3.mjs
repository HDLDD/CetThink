const q = (id, title, options, answer, explain = '') => ({ id, title, options, answer, explain });
const R = (id, title, passage, questions) => ({ id, title, passage, questions });
const C = (id, title, passage, blanks) => ({ id, title, passage, blanks });

function dedupe(arr) {
  const m = new Map();
  for (const x of arr || []) if (x && x.id != null) m.set(x.id, x);
  return [...m.values()];
}

function mkRead(id, title, para, qas) {
  return R(id, title, para, qas.map(([qid, qt, options, ans, ex]) => q(qid, qt, options, ans, ex || '')));
}

function mkCloze(id, title, text, blanks) {
  return C(id, title, text, blanks.map(([bid, options, ans, ex]) => ({ id: bid, options, answer: ans, explain: ex || '' })));
}

